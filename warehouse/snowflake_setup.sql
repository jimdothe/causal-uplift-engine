-- One-time Snowflake setup. Run as ACCOUNTADMIN. See docs/SETUP.md.
USE ROLE ACCOUNTADMIN;

-- Compute: smallest warehouse, suspends after 60 s idle to save credits.
CREATE WAREHOUSE IF NOT EXISTS UPLIFT_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Guardrail: stop the warehouse before trial credits run out.
CREATE OR REPLACE RESOURCE MONITOR UPLIFT_MONITOR WITH CREDIT_QUOTA = 50
  TRIGGERS ON 75 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE UPLIFT_WH SET RESOURCE_MONITOR = UPLIFT_MONITOR;

-- Storage
CREATE DATABASE IF NOT EXISTS CAUSAL_UPLIFT;
CREATE SCHEMA IF NOT EXISTS CAUSAL_UPLIFT.RAW;
CREATE SCHEMA IF NOT EXISTS CAUSAL_UPLIFT.STAGING;
CREATE SCHEMA IF NOT EXISTS CAUSAL_UPLIFT.VALIDATED;
CREATE SCHEMA IF NOT EXISTS CAUSAL_UPLIFT.ANALYTICS;

-- Roles
CREATE ROLE IF NOT EXISTS UPLIFT_PIPELINE;   -- automation (GitHub Actions)
CREATE ROLE IF NOT EXISTS UPLIFT_DEV;        -- team members
GRANT ROLE UPLIFT_PIPELINE TO ROLE SYSADMIN;
GRANT ROLE UPLIFT_DEV TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE UPLIFT_WH TO ROLE UPLIFT_PIPELINE;
GRANT USAGE ON WAREHOUSE UPLIFT_WH TO ROLE UPLIFT_DEV;
GRANT USAGE ON DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_PIPELINE;
GRANT USAGE ON DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_DEV;

-- Pipeline writes every schema.
GRANT ALL ON SCHEMA CAUSAL_UPLIFT.RAW TO ROLE UPLIFT_PIPELINE;
GRANT ALL ON SCHEMA CAUSAL_UPLIFT.STAGING TO ROLE UPLIFT_PIPELINE;
GRANT ALL ON SCHEMA CAUSAL_UPLIFT.VALIDATED TO ROLE UPLIFT_PIPELINE;
GRANT ALL ON SCHEMA CAUSAL_UPLIFT.ANALYTICS TO ROLE UPLIFT_PIPELINE;

-- Developers read everything and build dbt models in their own dev schemas (dbt target "dev").
GRANT USAGE ON ALL SCHEMAS IN DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_DEV;
GRANT SELECT ON ALL TABLES IN DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_DEV;
GRANT SELECT ON FUTURE TABLES IN DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_DEV;
GRANT CREATE SCHEMA ON DATABASE CAUSAL_UPLIFT TO ROLE UPLIFT_DEV;

-- Service user for GitHub Actions: key-pair auth only, no password.
CREATE USER IF NOT EXISTS UPLIFT_CI
  TYPE = SERVICE DEFAULT_ROLE = UPLIFT_PIPELINE DEFAULT_WAREHOUSE = UPLIFT_WH;
GRANT ROLE UPLIFT_PIPELINE TO USER UPLIFT_CI;
